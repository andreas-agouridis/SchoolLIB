def make_icon(name, color="#ffffff", size=22):
    key = (name, color, size)
    if key in _CACHE:
        return _CACHE[key]
    svg_template = _SVG.get(name)
    if not svg_template:
        return QIcon()
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" '
        f'fill="{color}">{svg_template}</svg>'
    )
    renderer = QSvgRenderer(BytesIO(svg.encode("utf-8")).getvalue())
    img = QImage(size, size, QImage.Format_ARGB32)
    img.fill(Qt.transparent)
    p = QPainter(img)
    renderer.render(p)
    p.end()
    icon = QIcon(QPixmap.fromImage(img))
    _CACHE[key] = icon
    return icon


def make_color_icon(name, size=22):
    return make_icon(name, color="#ffffff", size=size)


def make_sidebar_icon(name, active=False):
    color = "#ffffff" if not active else "#ffffff"
    return make_icon(name, color=color, size=20)


def make_button_icon(name, color="#ffffff", size=18):
    return make_icon(name, color=color, size=size)
